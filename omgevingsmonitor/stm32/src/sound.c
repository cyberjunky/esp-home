/*
 * sound.c - A-weighted SPL from the ICS-43434 (24-bit I2S, -26 dBFS @ 94 dB SPL).
 *
 * I2S runs from SYSCLK = HSI16 -> fs = 16 MHz / (64 * 16) = 15625 Hz.
 * A-weighting: 4 first-order high-pass sections + 1 fitted low-pass section
 * in Q30 fixed point (see tools/design_aweight.py, error < 0.2 dB from
 * 31.5 Hz to 7 kHz). Processing happens in the DMA half/full interrupts,
 * the core sleeps (WFI) in between. The mic is unclocked (power-down)
 * whenever we are not measuring.
 */
#include "sound.h"
#include <math.h>
#include "lowpower.h"
#include "stm32l0xx_hal.h"

#ifndef SOUND_SETTLE_MS
#define SOUND_SETTLE_MS 400     /* mic start-up (2^18 SCK) + filter settling */
#endif
#ifndef SOUND_MEASURE_MS
#define SOUND_MEASURE_MS 2000
#endif
#ifndef SOUND_CAL_DB
#define SOUND_CAL_DB 0.0f       /* per-unit calibration offset */
#endif
#define MIC_SENS_DBFS (-26.0f)
#define MIC_REF_DB_SPL 94.0f
#define FS_HZ 15625u
#define FAST_BLOCK (FS_HZ / 8)  /* 125 ms "fast" time weighting block */

/* generated by tools/design_aweight.py, fs = 15625 Hz, Q30 */
#define AW_HP0_P (1064884281)
#define AW_HP1_P (1064884281)
#define AW_HP2_P (1028237687)
#define AW_HP3_P (794522140)
#define AW_LP_Q (205383861)
#define AW_LP_P (-58330473)
#define AW_GAIN (0.938965467f)

#define FRAMES 256                         /* stereo frames in the DMA ring */
static uint16_t dma_buf[FRAMES * 4];       /* 2 ch x 2 halfwords (24-in-32) */

static I2S_HandleTypeDef hi2s;
static DMA_HandleTypeDef hdma;

static volatile uint32_t skip;             /* samples still to discard   */
static volatile uint32_t count;            /* samples accumulated        */
static volatile uint32_t target;
static volatile uint64_t energy, blk_energy, blk_max;
static volatile uint32_t blk_n;
static volatile uint64_t chan_act[2];      /* activity per channel       */
static int ch = -1;                        /* selected channel           */
static int32_t sx[5], sy[5], prev_raw[2];

static inline int32_t mulq30(int32_t a, int32_t b) {
  return (int32_t)(((int64_t)a * b + (1 << 29)) >> 30);
}

__attribute__((optimize("O2"))) static void process(const uint16_t *p, uint32_t frames) {
  static const int32_t hp[4] = {AW_HP0_P, AW_HP1_P, AW_HP2_P, AW_HP3_P};
  for (uint32_t f = 0; f < frames; f++, p += 4) {
    int32_t s[2];
    s[0] = (int32_t)((uint32_t)p[0] << 16 | p[1]) >> 8;
    s[1] = (int32_t)((uint32_t)p[2] << 16 | p[3]) >> 8;

    if (ch < 0) { /* settling: find the channel the mic actually drives */
      for (int c = 0; c < 2; c++) {
        int32_t d = (s[c] - prev_raw[c]) >> 6;
        chan_act[c] += (uint32_t)(d < 0 ? -d : d);
        prev_raw[c] = s[c];
      }
    }

    int32_t x = s[ch < 0 ? 0 : ch];
    for (int i = 0; i < 4; i++) {
      int32_t y = (x - sx[i]) + mulq30(hp[i], sy[i]);
      sx[i] = x;
      sy[i] = y;
      x = y;
    }
    int32_t y = x + mulq30(AW_LP_Q, sx[4]) + mulq30(AW_LP_P, sy[4]);
    sx[4] = x;
    sy[4] = y;

    if (skip) {
      skip--;
      continue;
    }
    if (count >= target) continue;
    uint64_t e = (uint64_t)((int64_t)y * y);
    energy += e;
    blk_energy += e;
    count++;
    if (++blk_n >= FAST_BLOCK) {
      if (blk_energy > blk_max) blk_max = blk_energy;
      blk_energy = 0;
      blk_n = 0;
    }
  }
}

void HAL_I2S_RxHalfCpltCallback(I2S_HandleTypeDef *h) { process(&dma_buf[0], FRAMES / 2); }
void HAL_I2S_RxCpltCallback(I2S_HandleTypeDef *h) { process(&dma_buf[FRAMES * 2], FRAMES / 2); }
void DMA1_Channel4_5_6_7_IRQHandler(void) { HAL_DMA_IRQHandler(&hdma); }

void HAL_I2S_MspInit(I2S_HandleTypeDef *h) {
  __HAL_RCC_SPI2_CLK_ENABLE();
  __HAL_RCC_DMA1_CLK_ENABLE();
  GPIO_InitTypeDef g = {.Pin = GPIO_PIN_12 | GPIO_PIN_13 | GPIO_PIN_15, .Mode = GPIO_MODE_AF_PP,
                        .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FREQ_LOW, .Alternate = GPIO_AF0_SPI2};
  HAL_GPIO_Init(GPIOB, &g);

  hdma.Instance = DMA1_Channel4;
  hdma.Init.Request = DMA_REQUEST_2;
  hdma.Init.Direction = DMA_PERIPH_TO_MEMORY;
  hdma.Init.PeriphInc = DMA_PINC_DISABLE;
  hdma.Init.MemInc = DMA_MINC_ENABLE;
  hdma.Init.PeriphDataAlignment = DMA_PDATAALIGN_HALFWORD;
  hdma.Init.MemDataAlignment = DMA_MDATAALIGN_HALFWORD;
  hdma.Init.Mode = DMA_CIRCULAR;
  hdma.Init.Priority = DMA_PRIORITY_HIGH;
  HAL_DMA_Init(&hdma);
  __HAL_LINKDMA(h, hdmarx, hdma);
  HAL_NVIC_SetPriority(DMA1_Channel4_5_6_7_IRQn, 1, 0);
  HAL_NVIC_EnableIRQ(DMA1_Channel4_5_6_7_IRQn);
}

void HAL_I2S_MspDeInit(I2S_HandleTypeDef *h) {
  HAL_NVIC_DisableIRQ(DMA1_Channel4_5_6_7_IRQn);
  HAL_DMA_DeInit(&hdma);
  __HAL_RCC_SPI2_CLK_DISABLE();
  __HAL_RCC_DMA1_CLK_DISABLE();
  /* clocks low (mic power-down), data pin analog */
  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_12 | GPIO_PIN_13, GPIO_PIN_RESET);
  GPIO_InitTypeDef g = {.Pin = GPIO_PIN_12 | GPIO_PIN_13, .Mode = GPIO_MODE_OUTPUT_PP,
                        .Pull = GPIO_NOPULL, .Speed = GPIO_SPEED_FREQ_LOW};
  HAL_GPIO_Init(GPIOB, &g);
  g.Pin = GPIO_PIN_15;
  g.Mode = GPIO_MODE_ANALOG;
  HAL_GPIO_Init(GPIOB, &g);
}

static void reset_state(void) {
  for (int i = 0; i < 5; i++) sx[i] = sy[i] = 0;
  prev_raw[0] = prev_raw[1] = 0;
  chan_act[0] = chan_act[1] = 0;
  energy = blk_energy = blk_max = 0;
  blk_n = count = 0;
  ch = -1;
}

static float to_db(float mean_sq) {
  /* full-scale 24-bit sine at MIC_SENS_DBFS corresponds to 94 dB SPL */
  const float fs = 8388608.0f;
  float ref = fs * powf(10.0f, MIC_SENS_DBFS / 20.0f);
  float ref_ms = ref * ref / 2.0f;
  if (mean_sq <= 0) return 0;
  return 10.0f * log10f(mean_sq * AW_GAIN * AW_GAIN / ref_ms) + MIC_REF_DB_SPL + SOUND_CAL_DB;
}

bool sound_measure(uint16_t *laeq_10, uint16_t *lamax_10) {
  reset_state();
  skip = (FS_HZ * SOUND_SETTLE_MS) / 1000u;
  target = 0; /* nothing counted until channel is chosen */

  hi2s.Instance = SPI2;
  hi2s.Init.Mode = I2S_MODE_MASTER_RX;
  hi2s.Init.Standard = I2S_STANDARD_PHILIPS;
  hi2s.Init.DataFormat = I2S_DATAFORMAT_24B;
  hi2s.Init.MCLKOutput = I2S_MCLKOUTPUT_DISABLE;
  hi2s.Init.AudioFreq = I2S_AUDIOFREQ_16K; /* -> 15625 Hz on 16 MHz */
  hi2s.Init.CPOL = I2S_CPOL_LOW;
  if (HAL_I2S_Init(&hi2s) != HAL_OK) return false;
  /* Size = number of 24/32-bit samples (HAL doubles it for halfwords) */
  if (HAL_I2S_Receive_DMA(&hi2s, dma_buf, FRAMES * 2) != HAL_OK) {
    HAL_I2S_DeInit(&hi2s);
    return false;
  }

  uint32_t t0 = HAL_GetTick();
  uint32_t limit = SOUND_SETTLE_MS + SOUND_MEASURE_MS + 1000u;
  bool ok = false;
  while (HAL_GetTick() - t0 < limit) {
    lp_kick();
    if (ch < 0 && skip == 0) {
      ch = chan_act[1] > chan_act[0] ? 1 : 0;
      /* reset filter states for the chosen channel, then a short re-settle */
      __disable_irq();
      for (int i = 0; i < 5; i++) sx[i] = sy[i] = 0;
      skip = FS_HZ / 10;
      target = (FS_HZ * SOUND_MEASURE_MS) / 1000u;
      __enable_irq();
    }
    if (target && count >= target) {
      ok = true;
      break;
    }
    __WFI();
  }
  HAL_I2S_DMAStop(&hi2s);
  HAL_I2S_DeInit(&hi2s);

  if (!ok || (chan_act[0] == 0 && chan_act[1] == 0) || energy == 0) return false;
  float leq = to_db((float)energy / (float)count);
  float lmax = blk_max ? to_db((float)blk_max / (float)FAST_BLOCK) : leq;
  if (lmax < leq) lmax = leq;
  *laeq_10 = (uint16_t)(leq * 10.0f + 0.5f);
  *lamax_10 = (uint16_t)(lmax * 10.0f + 0.5f);
  return true;
}
