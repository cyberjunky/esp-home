"""Design the fixed-point A-weighting filter used by stm32/src/sound.c.

The STM32L072 (Cortex-M0+, no FPU) cannot afford float biquads at audio rate,
so A-weighting is split into first-order sections that each cost a single
32x32->64 multiply:

  * four high-pass sections  y = (x - x1) + p*y1     (poles 20.6, 20.6, 107.7, 737.9 Hz)
  * one fitted low-pass/shelf y = x + q*x1 + p*y1     (approximates the 12194 Hz pole pair,
                                                       which lies above Nyquist at fs=15625)

The overall gain is applied afterwards, in float, to the mean-square energy.

Run:  python tools/design_aweight.py    -> prints a C snippet + error table.
"""
import numpy as np
from scipy.optimize import minimize

FS = 15625.0           # I2S sample rate on HSI16: 16 MHz / (64 * 16)
Q = 30                 # coefficient format
F1, F2, F3, F4 = 20.598997, 107.65265, 737.86223, 12194.217


def a_weight_db(f):
    f2 = f * f
    ra = (F4**2 * f2**2) / ((f2 + F1**2) * np.sqrt((f2 + F2**2) * (f2 + F3**2)) * (f2 + F4**2))
    return 20 * np.log10(ra) + 2.0


def hp_pole(fc):
    """Prewarped bilinear high-pass pole."""
    k = np.tan(np.pi * fc / FS)
    return (1 - k) / (1 + k)


def response(f, hp_poles, q, p_lp):
    z = np.exp(1j * 2 * np.pi * f / FS)
    h = np.ones_like(z)
    for p in hp_poles:
        h *= (1 - 1 / z) / (1 - p / z)
    h *= (1 + q / z) / (1 - p_lp / z)
    return h


hp = [hp_pole(F1), hp_pole(F1), hp_pole(F2), hp_pole(F3)]
fgrid = np.logspace(np.log10(20), np.log10(7000), 400)
target = a_weight_db(fgrid)


def err(params):
    q, p = params
    h = response(fgrid, hp, q, p)
    g = 1 / abs(response(np.array([1000.0]), hp, q, p)[0])
    d = 20 * np.log10(abs(h) * g) - target
    w = np.where(fgrid < 50, 0.3, 1.0)  # very low frequencies matter less
    return float(np.sum((w * d) ** 2))


res = minimize(err, x0=[0.0, 0.0], method="Nelder-Mead")
q_lp, p_lp = res.x
gain = 1 / abs(response(np.array([1000.0]), hp, q_lp, p_lp)[0])

to_q = lambda v: int(round(v * (1 << Q)))
print(f"/* generated by tools/design_aweight.py, fs = {FS:.0f} Hz, Q{Q} */")
for i, p in enumerate(hp):
    print(f"#define AW_HP{i}_P  ({to_q(p)})   /* {p:.9f} */")
print(f"#define AW_LP_Q   ({to_q(q_lp)})   /* {q_lp:.9f} */")
print(f"#define AW_LP_P   ({to_q(p_lp)})   /* {p_lp:.9f} */")
print(f"#define AW_GAIN   ({gain:.9f}f)  /* amplitude gain to 0 dB @ 1 kHz */")
print()


# -- bit-exact simulation of the C implementation -----------------------------
def sim_fixed(x):
    P = [to_q(p) for p in hp]
    qq, pl = to_q(q_lp), to_q(p_lp)
    rnd = 1 << (Q - 1)
    st_x = [0] * 5
    st_y = [0] * 5
    out = np.zeros(len(x))
    for n, v in enumerate(x):
        v = int(v)
        for i in range(4):
            y = (v - st_x[i]) + ((P[i] * st_y[i] + rnd) >> Q)
            st_x[i], st_y[i] = v, y
            v = y
        y = v + ((qq * st_x[4] + pl * st_y[4] + rnd) >> Q)
        st_x[4], st_y[4] = v, y
        out[n] = y
    return out


print(" f[Hz]   IEC A[dB]  float[dB]  fixed[dB]")
amp = 0.5 * (1 << 23)
for f in [31.5, 63, 125, 250, 500, 1000, 2000, 3150, 4000, 5000, 6300, 7000]:
    n = int(FS * 1.2)
    t = np.arange(n) / FS
    x = np.round(amp * np.sin(2 * np.pi * f * t))
    y = sim_fixed(x)[n // 3:]
    fixed_db = 20 * np.log10(np.sqrt(np.mean(y**2)) * gain / (amp / np.sqrt(2)))
    flt_db = 20 * np.log10(abs(response(np.array([f]), hp, q_lp, p_lp)[0]) * gain)
    print(f"{f:7.1f}  {a_weight_db(f):9.2f}  {flt_db:9.2f}  {fixed_db:9.2f}")
